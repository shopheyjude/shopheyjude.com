def page(path, title, desc, body, current="", base=None, social=None, jsonld=""):
    if base is None:
        base = "../" * path.count("/")
    if path not in NOINDEX_PAGES:
        SITEMAP.append(path)
    html = head(title, desc, base, social, path, jsonld) + "\n" + header(base, current) + "\n<main id=\"main\">\n" + body + "\n</main>\n" + footer(base)
    out = ROOT / path
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(html, encoding="utf-8")


