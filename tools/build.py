def clean_url(path):
    if path in ("", "index.html"):
        return SITE + "/"
    return SITE + "/" + (path[:-5] if path.endswith(".html") else path)


def ld(*objs):
    graph = [dict(o) for o in objs if o]
    if not graph:
        return ""
    data = {"@context": "https://schema.org", "@graph": graph}
    return '<script type="application/ld+json">' + _j.dumps(data, ensure_ascii=False).replace("</", "<\\/") + "</script>"


